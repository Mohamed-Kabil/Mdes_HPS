@app.get("/api/phase2/latest")
def api_phase2_latest():
    entries = get_release_notes_table(CACHE_DIR, refresh=False)
    if not entries:
        return jsonify({"error": "cache/known_releases.json not found or empty — run "
                                  "fetch_mc_source.py at least once first."}), 503

    entry = entries[0]
    text = fetch_note_text(entry, CACHE_DIR)
    matched_apis = find_matching_apis(text)
    parsed = parse_note(text, url=entry["url"]) if matched_apis else None

    return jsonify({
        "title": entry["title"],
        "url": entry["url"],
        "mdes_release": entry["mdes_release"],
        "note_type": entry["note_type"],
        "upgrade_date": entry["upgrade_date"],
        "tracked_apis": TARGET_APIS,
        "matched_apis": matched_apis,
        "parsed": parsed,
    })


