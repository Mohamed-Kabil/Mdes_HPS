# 3b. GET /api/mdes_cs_mapping — MDES Customer Service API -> Java field
#     mapping (generated externally, read-only here, see MDES_CS_MAPPING_JSON)
# ============================================================================

@app.get("/api/mdes_cs_mapping")
def api_mdes_cs_mapping():
    if not os.path.exists(MDES_CS_MAPPING_JSON):
        return jsonify({
            "error": f"Fichier introuvable : {MDES_CS_MAPPING_JSON} — régénérer avec "
                     "extract_java_field_mapping.py (voir MDES_CS_API_JAVA_MAPPING_LINK.md).",
        }), 503

    with open(MDES_CS_MAPPING_JSON, encoding="utf-8") as f:
        raw = json.load(f)

    operations = []
    for op in raw.get("operations", []):
        variants = []
        total_fields = 0
        unresolved_count = 0
        for variant_name, variant in op.get("variants", {}).items():
            fields = []
            flat_fields = mdes_cs_divergence_report.flatten_java_fields(variant.get("fields", {}))
            for field_path, info in flat_fields.items():
                fields.append({
                    "path": field_path,
                    "type": info.get("type"),
                    "source": info.get("source"),
                    "java_source": info.get("javaSource"),
                    "java_expr": info.get("javaExpr"),
                })
                total_fields += 1
                if info.get("source") == "unresolved":
                    unresolved_count += 1
            variants.append({
                "name": variant_name,
                "builder_method": variant.get("builderMethod"),
                "source_lines": variant.get("sourceLines"),
                "fields": fields,
            })
        operations.append({
            "operation": op.get("operation"),
            "path": op.get("path"),
            "internal_path": op.get("internalPath"),
            "java_file": op.get("javaFile"),
            "total_fields": total_fields,
            "unresolved_count": unresolved_count,
            "variants": variants,
        })

    return jsonify({
        "generated_at": raw.get("_meta", {}).get("generatedAt"),
        "source_tag_legend": raw.get("_meta", {}).get("sourceTagLegend", {}),
        "operations": operations,
    })


