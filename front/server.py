# 3. GET /api/reports — list of already-generated report/email files
# ============================================================================

@app.get("/api/reports")
def api_reports():
    if not os.path.isdir(REPORTS_DIR):
        return jsonify({"reports": []})

    reports = []
    for name in os.listdir(REPORTS_DIR):
        path = os.path.join(REPORTS_DIR, name)
        if not os.path.isfile(path):
            continue
        stat = os.stat(path)
        reports.append({
            "name": name,
            "size_bytes": stat.st_size,
            "modified_at": stat.st_mtime,
        })
    reports.sort(key=lambda r: r["modified_at"], reverse=True)
    return jsonify({"reports": reports})


@app.get("/reports/<path:name>")
def get_report_file(name):
    """Raw report file. send_from_directory uses Werkzeug's safe_join under
    the hood, so a name containing '..' can't escape REPORTS_DIR. Mimetype is
    guessed from the extension (.xlsx vs .md) instead of being hardcoded, so
    the Excel reports open correctly instead of downloading as plain text."""
    return send_from_directory(REPORTS_DIR, name)


