# 4. Actions — actually re-run a script, not just read the cache
#    (front/TASKS.md, step 4). Synchronous: the request blocks until the run
#    finishes, same as calling the CLI script directly — fine for a small
#    internal tool, no background job queue needed.
# ============================================================================

def _run_phase2_check(check_result, extra_fields=None):
    """Shared response-building tail for both phase2 check routes: writes
    the Excel report (one sheet per impacted tracked API) when 2+ releases
    impact tracked APIs, and shapes the JSON payload the front-end's outcome
    popup/email-preview flow expects. No .md file is written anywhere.
    NEVER sends — sending only happens from /api/phase2/send, after the
    user has reviewed (and optionally edited) the subject/body in the
    front-end popup."""
    relevant = check_result["relevant"]
    result = {
        "outcome": check_result["outcome"],
        "checked_count": len(check_result["working_set"]),
        "checked_titles": [e["title"] for e in check_result["working_set"]],
        "relevant": bool(relevant),
        **(extra_fields or {}),
    }

    if not relevant:
        return jsonify(result)

    matched_apis = sorted({api for r in relevant for api in r["matched_apis"]},
                           key=phase2_job_a_new_release_alert.TARGET_APIS.index)
    subject = phase2_job_a_new_release_alert.email_subject(relevant)
    body = phase2_job_a_new_release_alert.render_email_body(relevant)

    xlsx_path = phase2_job_a_new_release_alert.default_report_xlsx_path()
    os.makedirs(os.path.dirname(xlsx_path), exist_ok=True)
    phase2_job_a_new_release_alert.render_report_xlsx(relevant, xlsx_path)

    result.update({
        "report_path": xlsx_path,
        "matched_apis": matched_apis,
        "relevant_titles": [r["title"] for r in relevant],
        "subject": subject,
        "body": body,
    })
    return jsonify(result)


@app.post("/api/phase2/check-pending")
def api_phase2_check_pending():
    """'Vérifier après le dernier pre-dig' button: every release not yet
    reflected in pre-dig.yaml (Production date still in the future),
    recomputed fresh every call — independent of the checkpoint. The ONLY
    action that ADVANCES cache/phase2_checkpoint.json afterward (regardless
    of outcome) — the authoritative sweep that moves the reference point
    the other button (check-latest) compares against."""
    entries = phase2_job_a_new_release_alert.get_release_notes_table(CACHE_DIR, refresh=True)
    if not entries:
        return jsonify({"error": "Aucune release trouvée dans l'index Mastercard."}), 502

    check = phase2_job_a_new_release_alert.check_pending_since_predig(entries, CACHE_DIR)
    phase2_job_a_new_release_alert.advance_checkpoint(CACHE_DIR, entries)
    return _run_phase2_check(check)


@app.post("/api/phase2/check-latest")
def api_phase2_check_latest():
    """'Vérifier la dernière release' button: releases newer than whatever
    check-pending last examined (the persisted checkpoint). Deliberately
    does NOT advance the checkpoint itself, so repeated clicks keep
    re-showing the same still-new release(s) until check-pending runs
    again. Falls back to just the single newest table entry if
    check-pending has never been run yet (no checkpoint)."""
    entries = phase2_job_a_new_release_alert.get_release_notes_table(CACHE_DIR, refresh=True)
    if not entries:
        return jsonify({"error": "Aucune release trouvée dans l'index Mastercard."}), 502

    check = phase2_job_a_new_release_alert.check_since_checkpoint(entries, CACHE_DIR)
    return _run_phase2_check(check, extra_fields={"used_fallback": check["used_fallback"]})


@app.post("/api/phase2/send")
def api_phase2_send():
    """Actually sends the email via send_email.py, using whatever subject/
    body the front-end popup submits — i.e. possibly edited by the user
    after reviewing what /api/phase2/run prepared. This is the ONLY route
    that sends for phase 2; /api/phase2/run never does."""
    payload = request.get_json(silent=True) or {}
    subject, body = payload.get("subject"), payload.get("body")
    if not subject or not body:
        return jsonify({"error": "Objet et corps requis."}), 400

    report_path = payload.get("report_path")
    attachments = [report_path] if report_path and os.path.exists(report_path) else None
    try:
        sent_to = send_email_module.send_email(subject, body, attachments=attachments)
    except send_email_module.SmtpConfigError as e:
        return jsonify({"error": str(e)}), 502

    return jsonify({"sent_to": sent_to})


@app.post("/api/phase1/run")
def api_phase1_run():
    """Re-runs phase1_historical_audit.py's actual run() end to end: fresh
    pre-dig.yaml, full note-based audit since 'cutoff', report + email draft
    written. Always called with send=False — sending only happens from
    /api/phase1/send, after the user reviews/edits the draft in the popup.
    Can take a while (fetches/parses every release note since the cutoff),
    the request blocks until it's done."""
    payload = request.get_json(silent=True) or {}
    cutoff_str = payload.get("cutoff", "2025-01")

    try:
        cutoff = phase1_historical_audit.parse_cutoff(cutoff_str)
    except (ValueError, AttributeError):
        return jsonify({"error": f"Cutoff invalide : '{cutoff_str}' (attendu YYYY-MM)"}), 400

    audited_notes, subject, body = phase1_historical_audit.run(
        DEFAULT_DATA_YAML, cutoff, CACHE_DIR,
        phase1_historical_audit.DEFAULT_REPORT_XLSX_PATH,
        refresh=True, send=False,
    )

    return jsonify({
        "cutoff": cutoff_str,
        "releases_audited": len(audited_notes),
        "report_path": phase1_historical_audit.DEFAULT_REPORT_XLSX_PATH,
        "subject": subject,
        "body": body,
    })


