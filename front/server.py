def compute_phase1_priority_status():
    """Direct pre-dig.yaml vs data.yaml diff on the 5 priority endpoints —
    same check phase1_historical_audit.py's CLI report leads with, reused
    as-is. Reads whatever's already cached; does NOT hit the network (that's
    what running the real phase1_historical_audit.py script does)."""
    predig_path = os.path.join(CACHE_DIR, "pre-dig.yaml")
    if not os.path.exists(predig_path):
        return None
    data_spec = load_spec(DEFAULT_DATA_YAML, repair=True)
    predig_spec = load_spec(predig_path, repair=True)
    return audit_predig_vs_data_direct(predig_spec, data_spec)


def summarize_api_status(entry):
    """entry = one value from audit_predig_vs_data_direct()'s result dict.
    Collapses its field-level results into one overall status for a
    dashboard tile: worst of {non_implemente, partiel, implemente}, counting
    only 'reliable' mismatches (see phase1_historical_audit.py's
    MINOR_NOISE_ATTRS — minLength/required noise from data.yaml's generation
    style is excluded, same as the CLI report already does)."""
    if not entry.get("endpoint_exists_in_predig"):
        return {"status": "unknown", "reliable_issues": 0, "total_fields": 0}
    if not entry["endpoint_exists_in_data"]:
        return {"status": "non_implemente", "reliable_issues": len(entry["fields"]), "total_fields": len(entry["fields"])}

    reliable_problems = [f for f in entry["fields"] if f["status"] != "implemente" and f["reliable"]]
    if any(f["status"] == "non_implemente" for f in reliable_problems):
        status = "non_implemente"
    elif reliable_problems:
        status = "partiel"
    else:
        status = "implemente"
    return {"status": status, "reliable_issues": len(reliable_problems), "total_fields": len(entry["fields"])}


@app.get("/api/phase1")
def api_phase1():
    predig_direct = compute_phase1_priority_status()
    if predig_direct is None:
        return jsonify({
            "error": "cache/pre-dig.yaml not found — run phase1_historical_audit.py "
                     "(or fetch_mc_source.py) at least once first.",
        }), 503

    apis = []
    for path, display in PRIORITY_PATH_DISPLAY:
        entry = predig_direct[path]
        summary = summarize_api_status(entry)
        apis.append({
            "path": path,
            "display": display,
            **summary,
            "fields": entry["fields"],
        })

    field_clusters = group_shared_schema_fixes(predig_direct)
    shared_fixes = [{
        **target,
        "schemas": [p for p in summarize_schema_fix_clusters(field_clusters) if p["data_origin"] == target["data_origin"]],
    } for target in summarize_by_data_target(field_clusters)]

    return jsonify({"apis": apis, "shared_fixes": shared_fixes})


